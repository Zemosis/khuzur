export default function PixelIcon({ name, size = 16, color, className = "", title }) {
  const rows = ICONS[name];
  if (!rows) return null;

  const rects = [];
  rows.forEach((row, y) => {
    // Merge horizontal runs so a 64-pixel icon is a handful of rects.
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === "#") x += 1;
      rects.push(<rect key={`${y}-${start}`} x={start} y={y} width={x - start} height={1} />);
    }
  });

  return (
    <svg
      viewBox="0 0 8 8"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill={color || "currentColor"}
      className={`inline-block shrink-0 ${className}`}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {rects}
    </svg>
  );
}
